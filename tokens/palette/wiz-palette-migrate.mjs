const NOT_IN_PALETTE = {"#3ED98A": "WizGen", "#1FB86E": "WizGen", "#D6F5E6": "WizGen", "#F06ABC": "WizLab", "#D44FA3": "WizLab", "#FBDDEF": "WizLab"};
const NEW = {"#1C50B5": 1, "#163E8D": 1, "#D6E0F2": 1, "#7D3AB7": 1, "#622D8F": 1, "#E8DCF2": 1, "#C2A200": 1, "#977E00": 1, "#F4EED1": 1, "#367C14": 1, "#2A6110": 1, "#DBE7D5": 1, "#EF6C00": 1, "#BA5400": 1, "#FCE5D1": 1, "#DF3C8C": 1, "#AE2F6D": 1, "#F9DCEA": 1, "#BE2323": 1, "#941B1B": 1, "#F3D7D7": 1, "#23A4D8": 1};

const args = process.argv.slice(2);
const flag = (n) => args.includes("--" + n);
const opt = (n) => { const a = args.find((x) => x.startsWith("--" + n + "=")); return a ? a.slice(n.length + 3) : null; };
const root = path.resolve(args.find((a) => !a.startsWith("--")) || ".");
const skip = new Set((opt("skip") || "").split(",").map((s) => s.trim().toUpperCase()).filter(Boolean));
const EXT = /\.(css|scss|sass|less|js|mjs|cjs|jsx|ts|tsx|vue|svelte|astro|html?|json|svg|md|mdx|py|txt|yml|yaml|xml|jsonc|liquid|php)$/i;
const SKIPDIR = new Set(["node_modules", ".git", "dist", "build", ".next", ".output", ".wrangler", ".turbo", ".cache", "coverage", "__pycache__"]);
const SELF = path.resolve(process.argv[1] || "");

function* walk(d) {
  for (const e of fs.readdirSync(d, { withFileTypes: true })) {
    if (e.isDirectory()) { if (!SKIPDIR.has(e.name) && !e.name.startsWith(".")) yield* walk(path.join(d, e.name)); }
    else if (EXT.test(e.name)) yield path.join(d, e.name);
  }
}
const rgb = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16));
const dist = (a, b) => Math.hypot(...rgb(a).map((v, i) => v - rgb(b)[i]));
const keepCase = (src, dst) => (src === src.toLowerCase() ? dst.toLowerCase() : dst.toUpperCase());
const RE = /#([0-9a-fA-F]{6})([0-9a-fA-F]{2})?(?![0-9a-fA-F])/g;
const swap = (m, rgb, a) => keepCase("#" + rgb, MAP["#" + rgb.toUpperCase()].to) + (a || "");

const hits = [], near = [], other = [];
let files = 0, changed = 0;
for (const f of walk(root)) {
  if (path.resolve(f) === SELF || /tokens\.json$|wiz-palette-migrate/.test(f)) continue;   // the kit's own files
  let txt;
  try { txt = fs.readFileSync(f, "utf8"); } catch { continue; }
  files++;
  const rel = path.relative(root, f);
  txt.split(/\r?\n/).forEach((line, i) => {
    for (const m of line.matchAll(RE)) {
      const H = "#" + m[1].toUpperCase();
      if (MAP[H] && !skip.has(H)) hits.push({ file: rel, line: i + 1, old: m[0], new: swap(m[0], m[1], m[2]), wiz: MAP[H].wiz, role: MAP[H].role });
      else if (NOT_IN_PALETTE[H]) other.push({ file: rel, line: i + 1, code: m[0], wiz: NOT_IN_PALETTE[H] });
      else if (flag("near") && !MAP[H] && !NEW[H]) {
        let best = null;
        for (const k of Object.keys(MAP)) { const d = dist(H, k); if (d < 34 && (!best || d < best.d)) best = { k, d }; }
        if (best) near.push({ file: rel, line: i + 1, code: m[0], close_to: best.k, wiz: MAP[best.k].wiz, role: MAP[best.k].role, distance: Math.round(best.d) });
      }
    }
  });
  if (flag("write")) {
    // ONE pass: each code is read once and replaced by its target; a target is never read again
    const out = txt.replace(RE, (s, rgb, a) => { const H = "#" + rgb.toUpperCase(); return MAP[H] && !skip.has(H) ? swap(s, rgb, a) : s; });
    if (out !== txt) { fs.writeFileSync(f, out, "utf8"); changed++; }
  }
}

if (flag("json")) {
  console.log(JSON.stringify({ root, files, hits, near, not_in_palette: other, written: flag("write") ? changed : 0 }, null, 2));
} else {
  const ROLE = { c: "main", d: "dark", p: "pale", w: "text on white" };
  console.log(`\nWiz - new palette (28 Oct 2026) | ${root} | ${files} files read\n`);
  if (!hits.length) console.log("No old Wiz color code found.");
  for (const h of hits) console.log(`  ${h.file}:${h.line}   ${h.old} -> ${h.new}   ${h.wiz} (${ROLE[h.role] || h.role})`);
  if (near.length) {
    console.log(`\nShades CLOSE to an old color (hand-made?) - check them, never replaced automatically:`);
    for (const n of near) console.log(`  ${n.file}:${n.line}   ${n.code} ~ ${n.close_to} (${n.wiz}, distance ${n.distance})`);
  }
  if (other.length) {
    console.log(`\nWizGen / WizLab: not in the new palette, left as they are (Yoni decides):`);
    for (const o of other) console.log(`  ${o.file}:${o.line}   ${o.code}   ${o.wiz}`);
  }
  const byWiz = {};
  for (const h of hits) byWiz[h.wiz] = (byWiz[h.wiz] || 0) + 1;
  console.log(`\n${hits.length} old code(s): ${Object.entries(byWiz).map(([k, v]) => `${k} ${v}`).join(" | ") || "-"}`);
  console.log(flag("write") ? `${changed} file(s) changed.` : `Nothing was changed. To replace: --write (and --skip=#... for exceptions).`);
}
