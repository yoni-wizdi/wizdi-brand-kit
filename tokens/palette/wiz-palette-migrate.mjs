/* wiz-palette-migrate.mjs — move a project to the new Wiz product palette (28 Oct 2026).
   Kit: https://studio-wizdi.com/kit/  ·  no dependencies (Node 18+).

     node wiz-palette-migrate.mjs [folder]                 report only: every old code, where it is, what replaces it
     node wiz-palette-migrate.mjs [folder] --write         replace for real, in ONE single pass (never chained)
     node wiz-palette-migrate.mjs [folder] --near          also list shades CLOSE to an old color (hand-made tints)
     node wiz-palette-migrate.mjs [folder] --skip=#F28C28,#FFE3C8   codes to leave as they are (not a Wiz color there)
     node wiz-palette-migrate.mjs [folder] --json          report as JSON

   What is searched: 6-digit hex codes (#F28C28, #f28c28) and 8-digit ones with alpha (#F28C2880: the alpha is kept),
   any case; the original case is kept when replacing.
   Skipped folders: node_modules, .git, dist, build, .next, .output, .wrangler, hidden folders.
   "Wiz" (#23A4D8) does not change. WizGen and WizLab are not in the new palette: reported, never replaced.

   (generated by ops/kit-wizdi-2026-10-29/build_kit.py — fix the table in kit.py, not here) */
